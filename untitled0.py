# -------------------- 1. IMPORT LIBRARIES --------------------

import os
import glob
import torch
import numpy as np
import matplotlib.pyplot as plt

from google.colab import drive

from monai.transforms import (
    Compose,
    LoadImaged,
    EnsureChannelFirstd,
    ScaleIntensityRanged,
    CropForegroundd,
    RandCropByPosNegLabeld,
    RandFlipd,
    RandRotate90d,
    EnsureTyped,
    Lambdad
)

from monai.data import Dataset, DataLoader
from monai.networks.nets import UNet
from monai.losses import DiceLoss
from monai.metrics import DiceMetric
from monai.inferers import sliding_window_inference

from sklearn.model_selection import train_test_split


# -------------------- 2. MOUNT GOOGLE DRIVE --------------------

drive.mount('/content/drive')

data_dir = "/content/drive/MyDrive/intern/Task03_Liver"

images_dir = os.path.join(data_dir, "imagesTr")
labels_dir = os.path.join(data_dir, "labelsTr")

images = sorted(glob.glob(os.path.join(images_dir, "*.nii.gz")))
labels = sorted(glob.glob(os.path.join(labels_dir, "*.nii.gz")))

print("Total images:", len(images))
print("Total labels:", len(labels))

assert len(images) > 0, "No images found. Check your dataset path."
assert len(images) == len(labels), "Image and label counts differ."


# -------------------- 3. PREPARE IMAGE-LABEL PAIRS --------------------

label_map = {
    os.path.basename(path): path
    for path in labels
}

data_dicts = []

for image_path in images:
    filename = os.path.basename(image_path)

    assert filename in label_map, f"Missing label for {filename}"

    data_dicts.append({
        "image": image_path,
        "label": label_map[filename]
    })

print("Matched image-label pairs:", len(data_dicts))


# -------------------- 4. SPLIT DATASET --------------------

train_files, val_files = train_test_split(
    data_dicts,
    test_size=0.2,
    random_state=42
)

print("Training samples:", len(train_files))
print("Validation samples:", len(val_files))


# -------------------- 5. PREPROCESSING --------------------

train_transforms = Compose([
    LoadImaged(keys=["image", "label"]),

    EnsureChannelFirstd(keys=["image", "label"]),

    # CT intensity normalization
    ScaleIntensityRanged(
        keys=["image"],
        a_min=-100,
        a_max=400,
        b_min=0.0,
        b_max=1.0,
        clip=True
    ),

    # Binary segmentation: liver and tumor as foreground
    Lambdad(
        keys=["label"],
        func=lambda x: (x > 0).astype(np.uint8)
    ),

    # Crop irrelevant background
    CropForegroundd(
        keys=["image", "label"],
        source_key="image"
    ),

    # Random 3D patches for training
    RandCropByPosNegLabeld(
        keys=["image", "label"],
        label_key="label",
        spatial_size=(96, 96, 48),
        pos=1,
        neg=1,
        num_samples=2,
        image_key="image",
        image_threshold=0
    ),

    # Data augmentation
    RandFlipd(
        keys=["image", "label"],
        spatial_axis=0,
        prob=0.5
    ),

    RandFlipd(
        keys=["image", "label"],
        spatial_axis=1,
        prob=0.5
    ),

    RandRotate90d(
        keys=["image", "label"],
        prob=0.5,
        max_k=3,
        spatial_axes=(0, 1)
    ),

    EnsureTyped(keys=["image", "label"])
])


# Validation transformations without augmentation
val_transforms = Compose([
    LoadImaged(keys=["image", "label"]),

    EnsureChannelFirstd(keys=["image", "label"]),

    ScaleIntensityRanged(
        keys=["image"],
        a_min=-100,
        a_max=400,
        b_min=0.0,
        b_max=1.0,
        clip=True
    ),

    Lambdad(
        keys=["label"],
        func=lambda x: (x > 0).astype(np.uint8)
    ),

    CropForegroundd(
        keys=["image", "label"],
        source_key="image"
    ),

    EnsureTyped(keys=["image", "label"])
])


# -------------------- 6. CREATE DATALOADERS --------------------

train_ds = Dataset(
    data=train_files,
    transform=train_transforms
)

val_ds = Dataset(
    data=val_files,
    transform=val_transforms
)

train_loader = DataLoader(
    train_ds,
    batch_size=1,
    shuffle=True,
    num_workers=0
)

val_loader = DataLoader(
    val_ds,
    batch_size=1,
    shuffle=False,
    num_workers=0
)

print("DataLoaders created successfully!")


# -------------------- 7. CONFIGURE DEVICE --------------------

device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

print("Running on:", device)


# -------------------- 8. BUILD 3D U-NET --------------------

model = UNet(
    spatial_dims=3,
    in_channels=1,
    out_channels=2,
    channels=(16, 32, 64, 128, 256),
    strides=(2, 2, 2, 2),
    num_res_units=2
).to(device)

loss_function = DiceLoss(
    to_onehot_y=True,
    softmax=True
)

optimizer = torch.optim.Adam(
    model.parameters(),
    lr=1e-4
)

dice_metric = DiceMetric(
    include_background=False,
    reduction="mean"
)

print("3D U-Net model initialized!")


# -------------------- 9. TRAINING --------------------

max_epochs = 50

best_val_dice = 0.0

best_model_path = "/content/best_liver_unet.pth"

for epoch in range(max_epochs):

    model.train()
    epoch_loss = 0.0

    for batch_data in train_loader:

        inputs = batch_data["image"].to(device)
        targets = batch_data["label"].to(device)

        targets = (targets > 0).long()

        optimizer.zero_grad()

        outputs = model(inputs)

        loss = loss_function(outputs, targets)

        loss.backward()
        optimizer.step()

        epoch_loss += loss.item()

    epoch_loss /= max(len(train_loader), 1)

    # Validation
    model.eval()
    dice_metric.reset()

    with torch.no_grad():

        for val_data in val_loader:

            val_images = val_data["image"].to(device)
            val_labels = val_data["label"].to(device)

            val_labels = (val_labels > 0).long()

            val_outputs = sliding_window_inference(
                inputs=val_images,
                roi_size=(96, 96, 48),
                sw_batch_size=1,
                predictor=model,
                overlap=0.25
            )

            predictions = torch.argmax(
                val_outputs,
                dim=1,
                keepdim=True
            )

            dice_metric(
                y_pred=predictions,
                y=val_labels
            )

    val_dice = dice_metric.aggregate().item()
    dice_metric.reset()

    print(
        f"Epoch [{epoch + 1}/{max_epochs}] "
        f"Loss: {epoch_loss:.4f} "
        f"Validation Dice: {val_dice:.4f}"
    )

    # Save best model
    if val_dice > best_val_dice:

        best_val_dice = val_dice

        torch.save(
            model.state_dict(),
            best_model_path
        )

        print("Best model saved!")

print("\nTraining completed!")
print("Best validation Dice:", best_val_dice)


# -------------------- 10. LOAD BEST MODEL --------------------

model.load_state_dict(
    torch.load(
        best_model_path,
        map_location=device,
        weights_only=True
    )
)

model.eval()


# -------------------- 11. EVALUATE ONE VALIDATION SAMPLE --------------------

sample = val_ds[0]

image = sample["image"].unsqueeze(0).to(device)
label = sample["label"]

with torch.no_grad():

    output = sliding_window_inference(
        inputs=image,
        roi_size=(96, 96, 48),
        sw_batch_size=1,
        predictor=model,
        overlap=0.25
    )

    prediction = torch.argmax(
        output,
        dim=1
    ).squeeze(0).cpu().numpy()

image_np = image.squeeze(0).cpu().numpy()
label_np = label.squeeze(0).cpu().numpy()

# Calculate Dice score
intersection = np.logical_and(
    prediction == 1,
    label_np == 1
).sum()

denominator = (
    (prediction == 1).sum()
    + (label_np == 1).sum()
)

dice_score = (
    2.0 * intersection / denominator
    if denominator > 0
    else 1.0
)

print(f"\nValidation Dice Score: {dice_score:.4f}")


# -------------------- 12. VISUALIZE SEGMENTATION --------------------

foreground_slices = np.where(
    label_np.sum(axis=(0, 1)) > 0
)[0]

if len(foreground_slices) > 0:
    slice_idx = int(
        foreground_slices[len(foreground_slices) // 2]
    )
else:
    slice_idx = image_np.shape[2] // 2

fig, axes = plt.subplots(1, 3, figsize=(15, 5))

axes[0].imshow(
    image_np[:, :, slice_idx],
    cmap="gray"
)
axes[0].set_title("Original CT Scan")

axes[1].imshow(
    label_np[:, :, slice_idx],
    cmap="gray"
)
axes[1].set_title("Ground-Truth Mask")

axes[2].imshow(
    prediction[:, :, slice_idx],
    cmap="gray"
)
axes[2].set_title("Predicted Liver Region")

for ax in axes:
    ax.axis("off")

plt.tight_layout()
plt.show()


# -------------------- 13. SAVE MODEL TO GOOGLE DRIVE --------------------

save_path = "/content/drive/MyDrive/liver_unet_model.pth"

torch.save(
    model.state_dict(),
    save_path
)

print("\nModel saved successfully!")
print("Saved at:", save_path)
print("Best validation Dice:", best_val_dice)

